// Причины отказа при вступлении в команду приходят из teams_service по-английски
// и предназначены разработчику. Участнику нужен человеческий текст, поэтому
// сопоставляем их здесь, во фронте: на бэкенде эти строки — часть контракта,
// их переписывание сломало бы совместимость.
//
// Сопоставление по подстроке, а не по точному равенству: часть сообщений
// содержит подставленные значения (например роль пользователя).

const RULES = [
    [/already belong to another team|already belong to a team/i, "Вы уже состоите в команде. Сначала выйдите из неё."],
    [/Team is full/i, "Команда переполнена: в ней уже 4 участника — 3 преподавателя и 1 студент."],
    [/Team already has a student/i, "В команде уже есть студент. По правилам конкурса студент в команде один."],
    [/Team already has 3 teachers/i, "В команде уже трое преподавателей — больше по правилам конкурса нельзя."],
    [/Cannot add teacher/i, "Осталось одно место, и оно предназначено студенту: в команде должен быть ровно один студент."],
    [/Finish stage/i, "Сначала завершите этап «Я» — все восемь уроков конкурса."],
    [/Choose your organization/i, "Сначала выберите организацию в настройках профиля."],
    [/belongs to another organization/i, "Эта команда из другой организации. Команда собирается внутри одного колледжа."],
    [/Invite link is invalid/i, "Ссылка недействительна. Возможно, лидер выпустил новую — попросите актуальную."],
    [/Team not found/i, "Команда не найдена."],
    [/Profile not found/i, "Профиль не найден. Попробуйте войти заново."],
    [/cannot join teams/i, "Ваша роль не позволяет вступать в команды."],
    [/Only the team leader can see the invite link/i, "Ссылку-приглашение видит только лидер команды."],
    [/Only the team leader can reissue/i, "Перевыпустить ссылку может только лидер команды."],
    [/Only the team leader can remove members/i, "Исключать участников может только лидер команды."],
    [/leader cannot remove themselves/i, "Лидер не может исключить сам себя. Удалите команду, если нужно её распустить."],
    [/User is not a member of this team/i, "Этот участник не состоит в команде."],
    [/leader cannot leave the team/i, "Лидер не может выйти из команды. Её можно только удалить."],
];

export function translateTeamError(message, fallback = "Не удалось выполнить действие") {
    const text = String(message || "").trim();
    if (!text) return fallback;

    for (const [pattern, translation] of RULES) {
        if (pattern.test(text)) return translation;
    }

    return text;
}
