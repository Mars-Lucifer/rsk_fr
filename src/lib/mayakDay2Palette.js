// Цвет луча — не украшение, а связь картона с экраном. Тайл в руке оранжевый,
// и карточка на экране обязана быть того же оранжевого: ТЗ, раздел В9 требует
// одни коды на тайлах, поле, портале и карточках, а расхождение любой строки
// называет дефектом производства.
//
// Поэтому шесть цветов берутся импортом из общего источника, а не переписываются
// сюда числами. `fieldLayout.mjs` принадлежит направлению гайда мастера и здесь
// только читается; модуль там намеренно чистый — ни JSX, ни React, — поэтому его
// одинаково берут вебпак и `node --test`.
import { DIRS } from "../components/features/mayak-guide/fieldLayout.mjs";

// Позиция на тайле → луч. Порядок напечатан на картоне и не обсуждается:
// номер 13 на всех трёх столах — «Данные и аналитика».
const RAY_BY_POSITION = ["knowledge", "external", "analytics", "automation", "space", "security"];

// Цвета столов в общий источник не входят: у поля «МЫ» столов нет. На картоне
// СРЕДА почти белая (F3F3F3) — заливка такой светлоты на экране не читается,
// поэтому у неё своя, нейтральная того же назначения. Синий и красный —
// пересчёт печатных плашек ДЕЯТЕЛЬНОСТИ и СОЗНАНИЯ.
const TABLE_COLORS = { 1: "#6E6E68", 2: "#0066FF", 3: "#EB0D1A" };

const rayColorAt = (position) =>
    DIRS.find((dir) => dir.id === RAY_BY_POSITION[position - 1])?.color || null;

/**
 * Цвета для полосы карточки: один у детали и изделия, два у узла и переходника.
 *
 * Два — потому что на картоне грань пары раскрашена половинами в цвета обоих
 * лучей. Экран повторяет ровно это: человек видит на полосе тот же стык, что
 * лежит у него на столе.
 */
export function day2AccentColors(number) {
    const base = String(number ?? "").split(":")[0];
    return base
        .split("-")
        .map(Number)
        .filter(Number.isFinite)
        .map((tile) => {
            const position = tile % 10;
            return position === 0 ? TABLE_COLORS[Math.floor(tile / 10)] : rayColorAt(position);
        })
        .filter(Boolean);
}
