// Знаки ЗВЕЗДЫ: тридцать шесть клеток «луч × уровень» как система, а не как тридцать шесть
// картинок.
//
// Знак собирается из двух слоёв:
//   база   — предмет луча. Один силуэт на все шесть уровней, по нему луч и узнаётся;
//   слой   — состояние уровня. Одинаково кодируется у всех лучей, по нему читается зрелость.
//
// Отсюда правило, ради которого всё и затевалось: цвет кодирует луч, форма кодирует уровень.
// Если уровень начать кодировать ещё и цветом, два кода спорят, и клетка перестаёт читаться.
//
// Уровень — состояние организации целиком, не луча. Поднять один луч отдельно нельзя: на
// шкале ИЦЗ зрелость принадлежит организации, поэтому здесь нет и не должно появиться поля
// «уровень луча».
//
// Ни three, ни React: файл обязан проверяться тестом без сцены и без браузера.

