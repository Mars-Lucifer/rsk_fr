const rect = (x, y, w, h, fill = "none") => ({ k: "rect", x, y, w, h, fill });
const line = (x1, y1, x2, y2) => ({ k: "line", x1, y1, x2, y2 });
const circle = (cx, cy, r, fill = "none") => ({ k: "circle", cx, cy, r, fill });
const poly = (points, fill = "none") => ({ k: "poly", points, fill });
const arrow = (x1, y1, x2, y2, dashed = false) => ({ k: "arrow", x1, y1, x2, y2, dashed });
// Дуга задаётся центром и углами, а не строкой пути. Строка пути непроверяема: её границы
// нельзя посчитать, и первое же кольцо ушло за сетку незамеченным — в SVG это не падает,
// а молча обрезается.
const arc = (cx, cy, r, from, to) => ({ k: "arc", cx, cy, r, from, to });

// Зоны знака. База живёт в середине, слой уровня — по краям. Пока зоны не были разведены,
