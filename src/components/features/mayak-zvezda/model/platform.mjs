// Звезда-платформа: геометрия сцены, снятая с эталонных кадров.
//
// Эталоны лежат в public/zvezda-star/ — ref-l1.png (уровень −1) и ref-l6.png (+4). Числа
// здесь подогнаны под них, а не выведены: пропорции звезды, высота постамента и посадка
// маяка правятся по картинке, и другого способа их получить нет.
//
// Ни three, ни React: считается тестом без сцены.

import { LEVELS, RAYS } from "./zvezda.mjs";

// Луч 0 смотрит вверх-назад сцены, дальше по часовой. Порядок задан аббревиатурой З-В-Е-З-Д-А
// и не сортируется.
export function rayAngle(index) {
    return -Math.PI / 2 + (index * Math.PI) / 3;
}

export const STAR = {
    outer: 3.05, // до кончика луча
    inner: 1.28, // впадина между лучами
    thickness: 0.3,
    // Фаска по кромке лучей. На эталоне ребро плиты не острое: оно ловит свет узкой полосой,
    // и именно она рисует контур звезды на фоне того же тона. На 0.035 полоса была тоньше
    // пикселя и пропадала.
    bevel: 0.05,
};

export const PEDESTAL = {
    // Центр постамента стоит чуть внутри кончика: на эталоне тумба перекрывает конец луча,
    // а не висит за ним.
    at: 2.72,
    // Размер снят с эталона по якорю, не зависящему от ракурса: горизонтальный размах центров
    // ближней пары тумб. Наши были больше эталонных в 1.26 раза, и из-за этого шесть тумб
    // смыкались, съедая силуэт звезды — читалось «шесть блюдец», а не звезда.
    radius: 0.65,
    // Тумба прорастает сквозь платформу, а не стоит на ней. На эталоне луч входит в цилиндр
    // сбоку и шва между ними нет — это одна отливка. Прежняя посадка «низ тумбы вровень
    // с поверхностью платформы» давала отдельный диск, положенный сверху, с тенью по всей
    // окружности: тумбы читались наклейками, висящими над звездой.
    //
    // Высота поэтому считается от низа платформы, а не сама по себе: тумба опущена до её
    // подошвы и ещё немного ниже, чтобы стык уходил в тень, а не вылезал ступенькой.
    height: 0.46,
    // Насколько столешница поднята над поверхностью платформы. Это и есть вся видимая часть
    // тумбы сверху; остальное — в теле звезды.
    top: 0.1,
    // Фаска по верхней кромке. На эталоне кромка не острая: она ловит свет тонкой белой
    // линией, и именно эта линия отделяет столешницу от боковой стенки на белом фоне.
    chamfer: 0.022,
    // Бортик по краю столешницы. На эталоне поле тумбы чуть утоплено внутрь кромки — тумба
    // читается блюдцем, а не шайбой, и предмет на ней стоит в углублении, а не на блине.
    lip: 0.013,
    // Кольцо цвета лежит на верхней кромке, не на боку тумбы. Отношение rim/radius держится
    // около 0.9 — как на эталоне.
    rimRadius: 0.59,
    rimThickness: 0.014,
};

// Маяк: шесть ярусов по числу уровней плюс фонарь. Сужается кверху, поэтому радиусы заданы
// парами. Ярус светится, если уровень достигнут, — легенда для этого не нужна.
// Ствол сужается 1.45:1, как на эталоне. У нас было 2.3:1, и башня читалась конусом —
// поэтому верхний радиус здесь не уменьшен, а увеличен: конус лечится не заострением,
// а тем, что верх перестаёт быть заметно уже низа.
export const TOWER = {
    // Цоколь: 1.39 радиуса ствола — промер эталона даёт 1.41.
    baseRadius: 0.5,
    baseHeight: 0.13,
    // Приземистость снята с эталона профилем свечения: светящаяся часть ствола там 100 px
    // высотой при 88 px ширины внизу, то есть высота ствола примерно равна его диаметру
    // (1.14). У нас было 2.0 — ровно поэтому маяк читался фабричной трубой, а не маяком,
    // и никакая детализация этого не лечила. Ярусов у нас шесть против четырёх на эталоне,
    // поэтому взято 1.25: точное попадание в 1.14 при шести ярусах дало бы стенку тоньше
    // карниза.
    tierHeight: 0.15,
    rBottom: 0.36,
    rTop: 0.26,
    lanternRadius: 0.2,
    lanternHeight: 0.2,
    // Площадка галереи выносится за ярус: если радиус не превышает rTop, диск прячется
    // внутрь силуэта и ступени под фонарём не видно вовсе.
    galleryRadius: 0.28,
    galleryHeight: 0.026,

    // Цоколь двухступенчатый со светящейся щелью между ступенями. На эталоне лужа света
    // на платформе выходит из-под маяка щелью, а не от подсвеченного цилиндра целиком:
    // именно поэтому сам цоколь там читается белым, а свет — отдельным событием.
    plinthGap: 0.032,
    plinthTopRadius: 0.44,

    // Вертикальные стойки по окружности яруса — главная фактура эталона. Светится стенка,
    // а стойки и карнизы остаются белыми: без них ярус выходит ровной светящейся заливкой,
    // и башня читается лампой, а не строением. Их видно даже на общем плане, где маяк
    // высотой в сотню пикселей: они дают вертикальную штриховку по силуэту.
    //
    // Двенадцать, а не четырнадцать: после того как ярусы стали ниже и уже, четырнадцать
    // стоек смыкались в частокол и съедали светящуюся стенку между собой.
    staves: 12,
    staveWidth: 0.017,
    // Стойка выступает наружу стенки, иначе тонет в свечении вместе с ней.
    staveOut: 0.008,

    // Окна. На общем плане их не видно, но подлёт к лучу показывает маяк крупно, и без окон
    // ярус остаётся светящейся бочкой. Рамка накладная, а не проём: проём в цилиндре стоит
    // булевой операции, а на кадре разница между утопленной рамкой и накладной не читается.
    windowSize: 0.042,
    windowDepth: 0.006,

    // Карниз между ярусами. Прежние 0.014 давали ниточку: на эталоне это заметный обод
    // высотой около четверти яруса, и ступенчатость силуэта держится на нём.
    corniceHeight: 0.042,
    corniceOut: 1.13,

    // Сужение неравномерное. На эталоне ствол резко ужимается в первых двух ярусах и почти
    // не меняется выше — линейная интерполяция вместо этого давала ровный конус, из-за чего
    // маяк читался водонапорной башней. Показатель <1 переносит основную убыль вниз.
    taperCurve: 0.85,

    // Купол полусферический, не конус: конус превращает маяк в ракету. Под ним ободок,
    // на нём шпиль с шаром.
    domeSquash: 0.62,
    domeRim: 0.02,
    finialStem: 0.026,
    finialBall: 0.027,
    finialTip: 0.04,
};

// Углы вертикальных стоек. Отдельной функцией, потому что то же кольцо ставится и на
// ярусы, и на фонарь.
export function staveAngles() {
    return Array.from({ length: TOWER.staves }, (_, i) => (i * 2 * Math.PI) / TOWER.staves);
}

// Цоколь: нижняя ступень, светящаяся щель, верхняя ступень. Суммарно ровно baseHeight —
// посадка ствола от разбивки не уезжает.
export function plinth() {
    const gap = TOWER.plinthGap;
    const step = (TOWER.baseHeight - gap) / 2;
    return {
        bottom: { y: step / 2, radius: TOWER.baseRadius, height: step },
        glow: { y: step + gap / 2, radius: TOWER.baseRadius * 0.93, height: gap },
        top: { y: step + gap + step / 2, radius: TOWER.plinthTopRadius, height: step },
    };
}

// Венец: галерея, фонарь, ободок, купол, шпиль. Одной функцией, потому что элементы
// садятся друг на друга — подгонка одной высоты не должна разъезжать остальные.
export function crown() {
    const base = towerHeight();
    const galleryY = base + TOWER.galleryHeight / 2;
    const lanternBase = base + TOWER.galleryHeight;
    const lanternY = lanternBase + TOWER.lanternHeight / 2;
    const rimY = lanternBase + TOWER.lanternHeight + TOWER.domeRim / 2;
    const domeBase = lanternBase + TOWER.lanternHeight + TOWER.domeRim;
    const domeRadius = TOWER.lanternRadius * 1.06;
    const stemY = domeBase + domeRadius * TOWER.domeSquash + TOWER.finialStem / 2;
    const ballY = domeBase + domeRadius * TOWER.domeSquash + TOWER.finialStem + TOWER.finialBall * 0.8;
    const tipY = ballY + TOWER.finialBall * 0.8 + TOWER.finialTip / 2;
    return { galleryY, lanternY, rimY, domeBase, domeRadius, stemY, ballY, tipY, top: tipY + TOWER.finialTip / 2 };
}

export function tiers() {
    const out = [];
    for (let i = 0; i < LEVELS.length; i += 1) {
        const t = (i / LEVELS.length) ** TOWER.taperCurve;
        const tNext = ((i + 1) / LEVELS.length) ** TOWER.taperCurve;
        out.push({
            level: i + 1,
            y: TOWER.baseHeight + i * TOWER.tierHeight + TOWER.tierHeight / 2,
            height: TOWER.tierHeight,
            rBottom: TOWER.rBottom + (TOWER.rTop - TOWER.rBottom) * t,
            rTop: TOWER.rBottom + (TOWER.rTop - TOWER.rBottom) * tNext,
        });
    }
    return out;
}

export function towerHeight() {
    return TOWER.baseHeight + LEVELS.length * TOWER.tierHeight;
}

// Контур звезды: двенадцать вершин, внешние и внутренние через одну.
//
// Обход вершин через одну здесь применять нельзя, хотя он и рисуется одним росчерком: две
// наложенные треугольные петли дают гексаграмму, чужой символ. Проверено на набросках.
export function starOutline() {
    const pts = [];
    for (let s = 0; s < 12; s += 1) {
        const angle = -Math.PI / 2 + (s * Math.PI) / 6;
        const r = s % 2 === 0 ? STAR.outer : STAR.inner;
        pts.push([Math.cos(angle) * r, Math.sin(angle) * r]);
    }
    return pts;
}

export function pedestalAt(index) {
    const a = rayAngle(index);
    return [Math.cos(a) * PEDESTAL.at, PEDESTAL.top - PEDESTAL.height / 2, Math.sin(a) * PEDESTAL.at];
}

// Цветная жила по лучу: от края основания маяка до тумбы, вровень с поверхностью платформы.
export function inlay(index) {
    const a = rayAngle(index);
    const from = TOWER.baseRadius + 0.06;
    const to = PEDESTAL.at - PEDESTAL.radius * 0.45;
    return { angle: a, from, to, length: to - from, mid: (from + to) / 2 };
}

// Точка, куда встаёт камера при подъезде к лучу, и точка, на которую она смотрит.
export function rayCamera(index) {
    const a = rayAngle(index);
    const [x, , z] = pedestalAt(index);
    // Камера садится снаружи и выше тумбы: если подлетать по лучу изнутри, маяк закрывает
    // половину кадра, а тумба уходит за нижнюю кромку.
    //
    // Вынос считается от габарита тумбы, а не задан числом: тумбу уже пришлось ужать под
    // эталон, и зашитая дистанция от прежнего размера сажала камеру вплотную — тумба
    // не помещалась в кадр целиком.
    const out = PEDESTAL.radius * 5.2;
    // Боковой снос. Справа выезжает панель на четверть экрана, и тумба, стоящая по центру
    // кадра, оказывается наполовину под ней. Камера сдвигается поперёк луча, чтобы предмет
    // встал в середину свободной части, а не всего вьюпорта.
    const side = 0.62;
    const px = Math.sin(a) * side;
    const pz = -Math.cos(a) * side;
    return {
        position: [x + Math.cos(a) * out + px, PEDESTAL.top + 2.05, z + Math.sin(a) * out + pz],
        target: [x, PEDESTAL.top + 0.22, z],
        // Обзор снят длинным объективом; с двух единиц тумба в него не помещается.
        fov: 30,
    };
}

