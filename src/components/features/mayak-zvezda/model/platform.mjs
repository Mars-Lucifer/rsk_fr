// Звезда-платформа: геометрия сцены, снятая с эталонных кадров.
//
// Эталоны лежат в public/zvezda-star/ — ref-l1.png (уровень −1) и ref-l6.png (+4). Числа
// здесь подогнаны под них, а не выведены: пропорции звезды, высота постамента и посадка
// маяка правятся по картинке, и другого способа их получить нет.
//
// Ни three, ни React: считается тестом без сцены.

import { LEVELS, RAYS } from "./zvezda.mjs";

// Луч 0 смотрит вверх-назад сцены, дальше по часовой. Порядок задан аббревиатурой З-В-Е-З-Д-А
// и не сортируется.
export function rayAngle(index) {
    return -Math.PI / 2 + (index * Math.PI) / 3;
}

export const STAR = {
    outer: 3.05, // до кончика луча
    inner: 1.28, // впадина между лучами
    thickness: 0.3,
    bevel: 0.035,
};

export const PEDESTAL = {
    // Центр постамента стоит чуть внутри кончика: на эталоне тумба перекрывает конец луча,
    // а не висит за ним.
    at: 2.72,
    // Размер снят с эталона по якорю, не зависящему от ракурса: горизонтальный размах центров
    // ближней пары тумб. Наши были больше эталонных в 1.26 раза, и из-за этого шесть тумб
    // смыкались, съедая силуэт звезды — читалось «шесть блюдец», а не звезда.
    radius: 0.65,
    // Высота правится в той же порции, иначе тумба превращается в шайбу: на эталоне боковая
    // стенка составляет 0.36 радиуса, а при старой высоте с новым радиусом вышло бы 0.71.
    height: 0.24,
    // Кольцо цвета лежит на верхней кромке, не на боку тумбы. Отношение rim/radius держится
    // около 0.9 — как на эталоне.
    rimRadius: 0.59,
    rimThickness: 0.014,
};

// Маяк: шесть ярусов по числу уровней плюс фонарь. Сужается кверху, поэтому радиусы заданы
// парами. Ярус светится, если уровень достигнут, — легенда для этого не нужна.
// Ствол сужается 1.45:1, как на эталоне. У нас было 2.3:1, и башня читалась конусом —
// поэтому верхний радиус здесь не уменьшен, а увеличен: конус лечится не заострением,
// а тем, что верх перестаёт быть заметно уже низа.
export const TOWER = {
    baseRadius: 0.45,
    baseHeight: 0.13,
    tierHeight: 0.22,
    rBottom: 0.33,
    rTop: 0.23,
    lanternRadius: 0.18,
    lanternHeight: 0.22,
    // Площадка галереи выносится за ярус: если радиус не превышает rTop, диск прячется
    // внутрь силуэта и ступени под фонарём не видно вовсе.
    galleryRadius: 0.25,
};

export function tiers() {
    const out = [];
    for (let i = 0; i < LEVELS.length; i += 1) {
        const t = i / LEVELS.length;
        const tNext = (i + 1) / LEVELS.length;
        out.push({
            level: i + 1,
            y: TOWER.baseHeight + i * TOWER.tierHeight + TOWER.tierHeight / 2,
            height: TOWER.tierHeight,
            rBottom: TOWER.rBottom + (TOWER.rTop - TOWER.rBottom) * t,
            rTop: TOWER.rBottom + (TOWER.rTop - TOWER.rBottom) * tNext,
        });
    }
    return out;
}

export function towerHeight() {
    return TOWER.baseHeight + LEVELS.length * TOWER.tierHeight;
}

// Контур звезды: двенадцать вершин, внешние и внутренние через одну.
//
// Обход вершин через одну здесь применять нельзя, хотя он и рисуется одним росчерком: две
// наложенные треугольные петли дают гексаграмму, чужой символ. Проверено на набросках.
export function starOutline() {
    const pts = [];
    for (let s = 0; s < 12; s += 1) {
        const angle = -Math.PI / 2 + (s * Math.PI) / 6;
        const r = s % 2 === 0 ? STAR.outer : STAR.inner;
        pts.push([Math.cos(angle) * r, Math.sin(angle) * r]);
    }
    return pts;
}

export function pedestalAt(index) {
    const a = rayAngle(index);
    return [Math.cos(a) * PEDESTAL.at, PEDESTAL.height / 2, Math.sin(a) * PEDESTAL.at];
}

// Цветная жила по лучу: от края основания маяка до тумбы, вровень с поверхностью платформы.
export function inlay(index) {
    const a = rayAngle(index);
    const from = TOWER.baseRadius + 0.06;
    const to = PEDESTAL.at - PEDESTAL.radius * 0.45;
    return { angle: a, from, to, length: to - from, mid: (from + to) / 2 };
}

// Точка, куда встаёт камера при подъезде к лучу, и точка, на которую она смотрит.
export function rayCamera(index) {
    const a = rayAngle(index);
    const [x, , z] = pedestalAt(index);
    // Камера садится снаружи и выше тумбы: если подлетать по лучу изнутри, маяк закрывает
    // половину кадра, а тумба уходит за нижнюю кромку.
    //
    // Вынос считается от габарита тумбы, а не задан числом: тумбу уже пришлось ужать под
    // эталон, и зашитая дистанция от прежнего размера сажала камеру вплотную — тумба
    // не помещалась в кадр целиком.
    const out = PEDESTAL.radius * 5.2;
    // Боковой снос. Справа выезжает панель на четверть экрана, и тумба, стоящая по центру
    // кадра, оказывается наполовину под ней. Камера сдвигается поперёк луча, чтобы предмет
    // встал в середину свободной части, а не всего вьюпорта.
    const side = 0.62;
    const px = Math.sin(a) * side;
    const pz = -Math.cos(a) * side;
    return {
        position: [x + Math.cos(a) * out + px, PEDESTAL.height + 2.05, z + Math.sin(a) * out + pz],
        target: [x, PEDESTAL.height + 0.22, z],
        // Обзор снят длинным объективом; с двух единиц тумба в него не помещается.
        fov: 30,
    };
}

// Обзор снят с эталона двумя независимыми промерами.
//
// Угол возвышения — по эллиптичности круглых тумб: отношение малой оси к большой равно
// синусу угла. Выходит 37°, а не 34°, как было подобрано на глаз.
//
// Дистанция — из отношения перспективных размеров ближней и дальней тумбы: на эталоне
// 1.20, у нас было 1.33, то есть камера стояла заметно ближе и объектив был шире.
// Отсюда длинная дистанция при узком fov: конструкция занимает две трети ширины кадра,
// а перспектива почти не разъезжается.
export const OVERVIEW = {
    position: [0, 15.25, 19.75],
    target: [0, 0.35, 0],
    // 12 по промеру давало обрез: нижняя тумба уходила за кромку. Промер считал габарит
    // по звезде, не по тумбам, вынесенным за её кончики.
    fov: 14,
};

