// Три части рассказа: зачем, из чего, насколько. Нужны для списка глав — пятнадцать
// подряд идущих строк без заголовков читаются как свалка.
export function tourParts() {
    const out = [];
    TOUR.forEach((cue, index) => {
        const last = out[out.length - 1];
        if (last && last.part === cue.part) last.items.push({ index, ...cue });
        else out.push({ part: cue.part, items: [{ index, ...cue }] });
    });
    return out;
}

// Моменты переключения в секундах записи.
//
// Пока длительность совпадает с той, на которой сняты метки, берутся сами метки. Разошлась
// больше чем на две секунды — значит дорожка другая, и метки считаются по весу реплик:
// приблизительно, зато не мимо.
export function tourCues(durationSec) {
    if (Math.abs(durationSec - TOUR_AUDIO_SECONDS) <= 2) {
        return TOUR.map((cue) => ({ at: cue.at, level: cue.level, ray: cue.ray }));
    }
    const total = TOUR.reduce((s, c) => s + c.words, 0);
    let at = 0;
    return TOUR.map((cue) => {
        const start = at;
        at += (cue.words / total) * durationSec;
        return { at: start, level: cue.level, ray: cue.ray };
    });
}

// Какая реплика звучит в данный момент. Линейный поиск с конца: реплик пятнадцать, и это
// дешевле любой индексации.
export function tourCueIndexAt(cues, timeSec) {
    for (let i = cues.length - 1; i >= 0; i -= 1) {
        if (timeSec >= cues[i].at) return i;
    }
    return 0;
}
