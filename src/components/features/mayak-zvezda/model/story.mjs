function restCaption(level) {
    const stars = "★".repeat(level.n) + "☆".repeat(MAX_LEVEL - level.n);
    return `${stars}  «${level.name}»: ${level.about}`;
}

// Плоский список шагов. Плеер идёт по нему и ничего не знает ни про уровни, ни про фазы.
//
// `light` отделён от `level` намеренно: в такте «Сознание» комната уже нового уровня, и свет
// должен приехать туда же — именно смена света и читается как «поднялись».
export const STEPS = LEVELS.flatMap((level) => {
    const rest = {
        id: `rest-${level.n}`,
        level: level.n,
        light: level.n,
        phase: "rest",
        caption: restCaption(level),
        hold: HOLD.rest,
    };
    const transition = TRANSITIONS[level.n];
    if (!transition) return [rest];
    return [
        rest,
        ...PHASES.map((phase) => ({
            id: `${phase.id}-${level.n}`,
            level: level.n,
            light: phase.id === "mind" ? level.n + 1 : level.n,
            phase: phase.id,
            caption: transition[phase.id],
            hold: HOLD.phase,
        })),
    ];
});

export function stepIndexOf(level, phase = "rest") {
    const found = STEPS.findIndex((step) => step.level === level && step.phase === phase);
    return found < 0 ? 0 : found;
}

export function phaseById(id) {
    return PHASES.find((phase) => phase.id === id) ?? null;
}
