// «МЫ». Голос разбирает подробно только первый такт, а тактов четыре — остальные идут
// молча на своих обычных паузах. Речь не растягивается на движение, которого в ней нет:
// на такты 2–4 остаётся шесть секунд текста против шестнадцати секунд анимации, и
// растянуть одно на другое можно было бы только ускорив стол вдвое.
//
// Молчащих шагов на этой стороне нет вовсе, и это не украшение. Молчащий шаг идёт на
// своём натуральном ходе, а значит немой стол ровно настолько и длится: пять таких шагов
// подряд дают десять секунд, за которые зритель успевает решить, что звук кончился.
// Поэтому каждая фраза раздаётся всем шагам до следующей фразы, а не одному «своему».
// Плата — темп: на тактах 3 и 4 шаги идут примерно на пятую часть быстрее натуральных.
