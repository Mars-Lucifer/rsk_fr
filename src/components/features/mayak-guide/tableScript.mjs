// Сценарии партии для стола в 3D. Это те же две раскладки, что показывают 2D-плееры
// FieldPlayerYa и FieldPlayerMy на /mayak-guide, только шаг здесь не перерисовывает
// разметку, а отдаёт команды предметам: колоде, жетонам, миплам и звёздам.
//
// Шаг — это {phase, caption, hold, run(api)}. Плеер сцены вызывает run() при входе в шаг
// и держит кадр hold миллисекунд. Никакой геометрии и никакого three здесь нет намеренно:
// сценарий должен читаться как описание партии, а не как код анимации.
//
// api = { decks, jetons, meeples, stars } — императивные ручки групп сцены.

