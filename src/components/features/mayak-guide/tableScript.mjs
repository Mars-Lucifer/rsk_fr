export function buildMy() {
    const steps = [];
    let closed = 0;

    steps.push({
        phase: 0,
        hold: 2800,
        caption: "Шесть разделов колоды уходят из коробки набора на карточки направлений «ЗВЕЗДЫ». В каждом ровно шесть заданий — столько же, сколько задач направления за партию.",
        run: (api) => {
            api.decks.layout();
        },
    });

    // Первый такт показывают в полный рост, дальше стол идёт живее: движения те же и
    // уже знакомы, а голос про такты 2–4 говорит короче. Растянутый повтор одного и того
    // же жеста четырежды — самая скучная часть партии.
    const RUSH = 0.7;
    const pace = (takt, ms) => (takt === 0 ? ms : Math.round(ms * RUSH));

    PLANS.forEach((plan, takt) => {
        steps.push({
            phase: 1,
            hold: pace(takt, 2600),
            caption: `${TACTS[takt].label}: команда выбрала девять задач и выложила жетоны направлений рубашкой вверх. План зафиксирован.`,
            run: (api) => {
                api.decks.parkDealt();
                api.jetons.setTakt(takt);
                api.jetons.layTakt(takt);
            },
        });

        steps.push({
            phase: 2,
            hold: pace(takt, 3200),
            caption: `${TACTS[takt].label}: под каждый жетон из его раздела уходит карта задания. Девять карт ложатся перед полем — участники решают их через МАЯК-ОКО.`,
            run: (api) => {
                const row = readSlots(plan.length);
                plan.forEach((dir, cell) => api.decks.deal(DIRS[dir].id, row[cell]));
            },
        });

        closed += plan.length;
        steps.push({
            phase: 3,
            hold: pace(takt, 2800),
            caption: `${TACTS[takt].label} закрыт: карты ушли инспектору, девять жетонов перевёрнуты цветной стороной, девять звёзд встали на трек индекса. Всего закрыто ${closed} из 36.`,
            run: (api) => {
                api.decks.parkDealt();
                api.jetons.flipTakt(takt);
                plan.forEach((dir, cell) => api.stars.place(dir, cell * 0.09));
            },
        });
    });

    steps.push({
        phase: 4,
        hold: 3600,
        caption: "Все четыре такта пройдены. Шесть Звёзд-Джокеров, принесённых с этапа «Я», закрывают последнюю клетку каждого направления — без выполнения задания.",
        run: (api) => {
            api.stars.jokers();
        },
    });

    return withVoice(steps, MY_VOICE);
}
