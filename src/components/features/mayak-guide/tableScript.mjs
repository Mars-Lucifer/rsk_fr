// Ряд разбора: выданные задания ложатся у ближней кромки поля. На клетки и гексы карту
// класть нельзя — она 104 мм шириной, вдвое шире клетки такта, и накрыла бы соседей.
//
// Шаг вдоль ряда считается от числа карт, а не фиксирован. Постоянный шаг был подобран
// под девятку такта «МЫ», и шесть карт специализации на нём лезли друг на друга без
// нужды: места в ряду хватало. Теперь карты расходятся настолько, насколько позволяет
// ширина полотна, и наползают только когда иначе не влезают.
//
// Ряд центрируется по числу карт: девять на такт «МЫ», шесть на такт специализации «Я»,
// одна на одиночное задание.
const CARD_W = CARD_MM.w / 1000;
const ROW_SPAN = 0.68; // ряд не выходит за ширину полотна
const LOOSE = CARD_W + 0.008; // карты рядом, но не касаются

// Экспортируется ради живого стола: там карты кладут те же руки в тот же ряд разбора,
// и второй набор координат для них означал бы, что демонстрация и занятие раскладывают
// карты по-разному.
export function readSlots(count) {
    if (count < 2) return [{ x: 0, z: READ_ROW.z, spin: 0, level: 0 }];
    // Ширину ряда задаёт (count − 1) шагов плюс одна целая карта, а не count шагов:
    // крайние карты выступают за крайние центры на полширины каждая. Раньше делили
    // span на count, и ряд из девяти вылезал за полотно на 29 мм.
    const step = Math.min(LOOSE, (ROW_SPAN - CARD_W) / (count - 1));
    // Лесенка по высоте нужна только там, где карты реально перекрываются: девять карт
    // такта «МЫ» без нахлёста заняли бы 936 мм при полотне 700. Шесть карт «Я» лежат
    // порознь, и подъём каждой следующей читался бы как «карты свалены друг на друга».
    const stacked = step < CARD_W;
    return Array.from({ length: count }, (_, i) => ({
        x: (i - (count - 1) / 2) * step,
        z: READ_ROW.z,
        spin: 0,
        level: stacked ? i : 0,
    }));
}

