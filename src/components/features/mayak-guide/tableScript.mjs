// Шаги одной фазы идут подряд — это и есть группа. Окно фразы раскладывается по группе
// пропорционально исходным паузам: фаза длится ровно столько, сколько звучит её фраза,
// а внутри сохраняется прежний ритм. seek стоит только на первом шаге группы: дальше
// дорожка играет сама, и лишняя перемотка дала бы щелчок на каждом шаге.
function withVoice(steps, windows) {
    const groups = [];
    steps.forEach((step, index) => {
        if (index > 0 && steps[index - 1].phase === step.phase) groups[groups.length - 1].push(step);
        else groups.push([step]);
    });

    return groups.flatMap((group, order) => {
        const window = windows[order] ?? null;
        if (!window) return group.map((step) => ({ ...step, seek: null, mute: true }));
        const span = window[1] - window[0];
        const total = group.reduce((sum, step) => sum + step.hold, 0);
        return group.map((step, index) => ({
            ...step,
            hold: Math.round((span * 1000 * step.hold) / total),
            seek: index === 0 ? window[0] : null,
            mute: false,
        }));
    });
}

const spots = (point, spread) => MEEPLE_COLORS.map((_, i) => pxYa(cluster(point, i, spread)));

// Порядок выдачи на такте специализации: слева направо по месту паза на поле, а не по
// обходу кольца. Считается один раз — раскладка поля от шага к шагу не меняется.
const DEAL_ORDER = [...TYPES].sort((a, b) => pxYa(a.deck).x - pxYa(b.deck).x);

// Прошлые задания уезжают в руку команды почти секунду. Новые выходят из стопок с
// задержкой, иначе в кадре двенадцать карт идут навстречу на одной высоте. Полностью
// дожидаться нельзя: шаг специализации длится 1.81 с, и карта, вышедшая на 1.05 с,
// не успевает долететь. 0.45 с — предел, при котором последняя ложится на 1.70 с.
const DEAL_WAIT = 0.45;
const DEAL_STAGGER = 0.06;

