export function buildYa() {
    const steps = [];

    steps.push({
        phase: 0,
        hold: 2800,
        caption: "Семь стопок уходят из коробки набора на свои гексы: шесть колод по типам контента и раздел «Старт» в верхнем правом углу. Миплы встают на центральный гекс СТАРТ.",
        run: (api) => {
            api.decks.layout();
            api.meeples.moveTo(spots(CENTER, 1));
        },
    });

    INNER.forEach((cell, index) => {
        steps.push({
            phase: 1,
            hold: 2200,
            caption: `Внутренний круг, стартовое задание ${index + 1} из 4. Карта берётся из стопки «Старт», команда решает её вместе и двигается дальше по кольцу.`,
            run: (api) => {
                api.decks.parkDealt();
                api.meeples.moveTo(spots(cell, 0.86));
                api.decks.deal("start", READ_ONE);
            },
        });
    });

    // Кольцо команда обходит вместе и на каждой ячейке решает задание этого типа. Карта
    // после этого уходит инспектору, как любое сданное задание, а не возвращается в
    // стопку: раздел отдаёт за партию пять карт из шести — одну здесь и четыре на
    // специализации.
    TYPES.forEach((type) => {
        steps.push({
            phase: 2,
            hold: 2200,
            caption: `Внешний круг, ${type.name.toLowerCase()}: команда встаёт на ячейку кольца, берёт карту этого типа и выполняет задание вместе. Карта уходит инспектору.`,
            run: (api) => {
                api.decks.parkDealt();
                api.meeples.moveTo(spots(type.sector, 0.95));
                api.decks.deal(type.id, READ_ONE);
            },
        });
    });

    // Расхождение — это уже первый такт специализации, а не подготовка к нему: участник
    // встал на ячейку своего типа и сразу берёт с неё первую карту. Дальше три гекса
    // луча — всего четыре задания, ровно столько карт в разделе.
    for (let level = 0; level < 4; level += 1) {
        const at = (type) => (level === 0 ? type.sector : type.ray[level - 1]);
        // Новые карты выходят не сразу: прошлые задания ещё едут со стола инспектору.
        // Но и ждать их полностью нельзя — окно фразы держит шаг 1.81 с, а полёт карты
        // 0.95 с плюс очередь до 0.30 с. При полной паузе последняя карта приземлялась
        // на 2.30 с, то есть следующий шаг сметал её прямо из воздуха.
        const wait = DEAL_WAIT;
        steps.push({
            phase: 3,
            hold: 2400 + wait * 1000,
            caption:
                level === 0
                    ? "Участники расходятся по своим типам. Расхождение — уже такт: каждый встаёт на ячейку своего типа и берёт с неё карту, задание 1 из 4."
                    : `Задание ${level + 1} из 4: каждый мипл делает шаг по лучу и берёт следующую карту своего типа. Стопка на глазах убывает — карт в разделе ровно четыре.`,
            run: (api) => {
                api.decks.parkDealt();
                api.meeples.moveTo(TYPES.map((type) => pxYa(at(type))));
                const row = readSlots(TYPES.length);
                // Карты ложатся в ряд в том же порядке, в каком стоят их пазы на поле.
                // По индексу в TYPES (обход кольца по часовой стрелке) шесть карт летели
                // наперекрёст через центр: правый паз ехал в левый край ряда и наоборот,
                // и три пары проходили ровно сквозь друг друга.
                DEAL_ORDER.forEach((type, place) => api.decks.deal(type.id, row[place], wait + place * DEAL_STAGGER));
            },
        });
    }

    steps.push({
        phase: 4,
        hold: 3600,
        caption: "Четыре такта специализации — четыре выполненных задания у каждого. Участник приносит команде красную Звезду-Джокер.",
        run: (api) => {
            api.decks.parkDealt();
            TYPES.forEach((type, order) => {
                const at = pxYa(outward(type.ray[2], 78));
                api.stars.joker(at, order * 0.12);
            });
        },
    });

    return withVoice(steps, YA_VOICE);
}

