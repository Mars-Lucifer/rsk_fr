// бейджа с номером, поэтому в 3D показываются только маркеры лица.
export const CARD_DECK_BACK_IMG = "/mayak-guide/deck-ya/text-back.png";

// Печатная страница набора — 111.1 × 154.2 мм с вылетами под обрез, чистая карта —
// 104 × 145. Растры колоды (deck-ya, deck-my) обрезаны до чистого формата, а проценты
// ниже сняты по странице: на обрезанной карте они уезжают на полвылета. Пересчёт
// линейный и делается один раз — иначе пришлось бы держать две таблицы координат.
const PAGE = { w: 111.1, h: 154.2 };
const CARD = { w: 104, h: 145 };
const BLEED_X = (((PAGE.w - CARD.w) / 2) / CARD.w) * 100;
const BLEED_Y = (((PAGE.h - CARD.h) / 2) / CARD.h) * 100;

export function cropBox(box) {
    return {
        x: (box.x * PAGE.w) / CARD.w - BLEED_X,
        y: (box.y * PAGE.h) / CARD.h - BLEED_Y,
        w: (box.w * PAGE.w) / CARD.w,
        h: (box.h * PAGE.h) / CARD.h,
    };
}

