// История перехода организации с уровня на уровень, на генерённых кадрах.
//
// Почему кадры, а не 3D: камера здесь одна и состояния известны заранее — в такой задаче
// генерация даёт качество, которого коробками из three за разумное время не добиться.
// 3D-прототип доказал механику тактов и задал композицию кадров, после чего был удалён:
// держать неподключённый файл ради истории — способ через месяц не понять, что живое.
// Он есть в истории ветки, если понадобится.
//
// Все кадры сняты с одного ракурса и приведены к общему холсту 1672 × 941, комната в них
// занимает один и тот же прямоугольник. Без этого кроссфейд читается как смена картинки,
// а не как изменение одной комнаты, и вся идея разваливается.
//
// Уровень поднимается НЕ в начале перехода, а в конце: пока цикл не пройден целиком,
// организация остаётся на прежнем уровне, даже если технику уже завезли. Это ровно тезис
// методички — мало купить, надо освоить и начать работать иначе.

