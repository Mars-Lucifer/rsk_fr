// Типы организации. Обстановка одна и та же — меняется только подпись, и этим
// доказывается, что модель не про колледж, а про организацию вообще.
export const ORG_KINDS = ["Колледж", "Завод", "Больница", "Департамент"];

// Держим кадр столько, сколько нужно, чтобы прочитать подпись и заметить, что изменилось.
// Кадры покоя стоят дольше: на них смотрят как на итог, а не как на шаг.
export const HOLD = { rest: 4600, phase: 3800 };

export function holdOf(frame) {
    return frame.phase ? HOLD.phase : HOLD.rest;
}
