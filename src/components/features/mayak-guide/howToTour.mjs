// «Как это работает» для МАЯК-ОКО. Два разных экрана — два разных разбора.
//
// Раньше набор был один на оба, и на главной половина шагов висела с надписью «ждём,
// пока это появится»: там нет ни номера задания, ни таймера, ни материалов. Экран без
// сессии и экран задания отвечают на разные вопросы, поэтому и текст у них разный.
//
// Главная объясняет устройство инструмента: что такое шесть типов, откуда берутся
// сервисы, зачем собирать промт. Экран задания объясняет ход работы: как открыть свою
// карту по номеру, что даёт «Начать задание», где искать материалы.

// Раздел колоды по номеру задания — тем же правилом, что и сам тренажёр
// (getRange в useMayakTaskManager). Держим свою копию из трёх строк, а не тянем хук:
// он реактовский, а нам нужен просто расчёт.
export function rangeOf(taskNumber) {
    const start = Math.floor((Number(taskNumber) - 1) / 100) * 100 + 1;
    return `${start}-${start + 99}`;
}

// Задание для разбора выбирается из настоящей колоды этого доступа, а не задаётся
// числом в коде: у каждой колоды свои номера, и «например №410» из чужого набора
// участника только запутает. Берём первое задание с приложенными материалами —
// на нём разбор показывает все три кнопки разом; если таких нет, берём просто первое.
export function pickSampleTask(tasks) {
    const list = Array.isArray(tasks) ? tasks : [];
    if (!list.length) return null;
    const rich = list.find((task) => task.hasFile && (task.hasInstruction || task.hasSource));
    const some = rich || list.find((task) => task.hasFile || task.hasInstruction || task.hasSource);
    const task = some || list[0];
    return {
        number: task.number,
        hasFile: Boolean(task.hasFile),
        hasInstruction: Boolean(task.hasInstruction),
        hasSource: Boolean(task.hasSource),
    };
}

