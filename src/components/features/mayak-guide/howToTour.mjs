// «Как это работает» для МАЯК-ОКО. Два разных экрана — два разных разбора.
//
// Раньше набор был один на оба, и на главной половина шагов висела с надписью «ждём,
// пока это появится»: там нет ни номера задания, ни таймера, ни материалов. Экран без
// сессии и экран задания отвечают на разные вопросы, поэтому и текст у них разный.
//
// Главная объясняет устройство инструмента: что такое шесть типов, откуда берутся
// сервисы, зачем собирать промт. Экран задания объясняет ход работы: как открыть свою
// карту по номеру, что даёт «Начать задание», где искать материалы.

// Задание для разбора выбирает сам разбор, а не участник: тренажёр отдаёт свою колоду
// (ту, что открыта этим доступом), из неё берётся самая «богатая» карта, и разбор сразу
// её открывает. Просить ввести номер было бесполезно: у каждой колоды свои номера,
// а на пустом задании №0 кнопок материалов вообще нет — половина шагов висела
// с надписью «ждём, пока это появится на экране».
//
// Чем больше у карты приложено, тем полнее выйдет разбор: на карте с файлом,
// инструкцией, источником и ссылкой на сервис видно всю цепочку целиком. Веса —
// порядок важности, а не оценка: файл важнее источника, потому что без него
// задание нечем выполнять.
export function pickSampleTask(tasks, { from = 0, to = Number.MAX_SAFE_INTEGER } = {}) {
    const list = Array.isArray(tasks) ? tasks : [];
    // Считаем по имени файла, а не по флагу: рантайм рисует кнопку только когда есть
    // и флаг, и файл на диске (reconcileTasksToDisk обнуляет имя, если файла нет).
    // По одному флагу разбор выбирал бы карту с несуществующим материалом.
    const has = { file: (t) => t?.hasFile && t?.file, instruction: (t) => t?.hasInstruction && t?.instruction, source: (t) => t?.hasSource && t?.sourceLink };
    const weigh = (task) =>
        (has.file(task) ? 8 : 0) + (task?.toolLink1 ? 4 : 0) + (has.instruction(task) ? 2 : 0) + (has.source(task) ? 1 : 0);

    let best = null;
    let bestWeight = -1;
    // Границы — то, что доступу разрешено открывать: goToTask в тренажёре молча
    // игнорирует индекс вне диапазона, и разбор рассказывал бы про карту, которая
    // на экране так и не появилась.
    for (let i = Math.max(0, from); i <= Math.min(to, list.length - 1); i++) {
        const task = list[i];
        if (!task?.number) continue;
        const weight = weigh(task);
        if (weight > bestWeight) {
            best = { task, index: i };
            bestWeight = weight;
        }
    }
    if (!best) return null;

    const { task, index } = best;
    return {
        index,
        number: task.number,
        hasFile: Boolean(has.file(task)),
        hasInstruction: Boolean(has.instruction(task)),
        hasSource: Boolean(has.source(task)),
        hasMap: Boolean(task.hasMap && task.map),
        toolName: task.toolLink1 ? String(task.toolName1 || "Инструмент") : "",
    };
}

function byText(text) {
    return [...document.querySelectorAll("button")].find((node) => node.textContent.trim().startsWith(text)) || null;
}

