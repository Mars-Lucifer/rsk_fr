// Сценарии подсказок для кабинета мастера: сначала консоль доступа, потом дашборд.
// Стрелка ведёт мастера по его же экрану и требует настоящих действий.
//
// Почему поверх живых экранов, а не отдельной страницей с картинками: после «инструкции
// слайдами» мастер всё равно возвращается на настоящий экран и ищет кнопку заново. Здесь
// он нажимает ту самую кнопку, и шаг закрывается фактом — сессия появилась в списке,
// ссылка скопирована. Пролистать, не сделав, нельзя.
//
// Цели ищутся по data-tour в консоли и по фрагменту имени CSS-модуля в дашборде. Второе
// выглядит хрупко, но альтернатива хуже: дашборд принадлежит другому направлению, и
// девять чужих атрибутов ради подсказок — это девять поводов для конфликта при слиянии.
// Имена модулей меняются реже, чем вёрстка, а если поменяются — шаг честно скажет
// «ждём, пока это появится», вместо того чтобы показать стрелку в пустоту.

// Флаг перехода между экранами: консоль ставит его на старте своей инструкции, дашборд
// читает при загрузке и сам продолжает с места, где консоль закончила. Через параметр
// адреса не сделать — мастер-ссылку строит сервер, и дописать к ней ничего нельзя.
export const TOUR_HANDOFF_KEY = "mayak-guide-tour-handoff";

function sessionCount() {
    return document.querySelectorAll('[data-tour="session"]').length;
}

