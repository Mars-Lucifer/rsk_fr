// Один источник правды для всех групп сцены. Жетоны, карты, звёзды и миплы обязаны
// возвращаться ровно туда, откуда их взяли: переворот поля начинается с того, что стол
// расчищают, и без общих координат «убрать всё» превращается в набор несогласованных
// чисел, разъезжающихся при каждой правке.
//
// Единицы — метры сцены. Поле лежит в центре стола и занимает 0.70 × 0.55 м,
// то есть x ∈ [-0.35, 0.35], z ∈ [-0.275, 0.275]. Всё, что ниже, стоит вне этого прямоугольника.

export const TABLE = { w: 2.4, d: 1.6, thickness: 0.04 };

// Анизотропная фильтрация текстур. На столе все предметы лежат плашмя и видны под углом,
// а это худший случай для мипмапов: без анизотропии дальняя половина поля и карт мылится
// независимо от разрешения растра. 16 — предел большинства GPU; three сам ужимает
// значение до реального максимума устройства, поэтому запрашивать можно смело.
export const MAX_ANISOTROPY = 16;

// Полотно поля — ткань, физика про него не знает. Но жетоны кладут НА него, поэтому под
// полотном лежит невидимая плита в толщину ткани: без неё жетоны проваливались бы к столу.
export const CLOTH_SURFACE = 0.004;

// Карта набора: 104 × 145 мм. Это не догадка и не пропорция PDF, а обмер самого поля —
// паз направления на стороне «МЫ» занимает 207 × 291 px растра 1400 × 1105, лепесток под
// стопку на стороне «Я» — 297 × 411 px вектора 1984 × 1559. Оба дают одно и то же.
// Страница печатного PDF крупнее (111 × 154 мм): там вылеты под обрез, они срезаны.
export const CARD_MM = { w: 104, h: 145, thickness: 0.4, corner: 4 };

// Колода набора: обе стороны лежат на столе одновременно, двумя рядами за полем.
// Дальний ряд — семь разделов «Я», ближний — шесть направлений «МЫ»: в кадре они
// читаются сверху вниз, и первым идёт этап, с которого начинают партию. Так виден весь
// набор целиком, а раскладка и переворот читаются как «стопки уехали на поле и
// вернулись на своё место», а не как подмена колоды.
//
// Ряд идёт поперёк стола, а не в глубину: колонка уходит в перспективу, и дальние
// подписи в ней становятся нечитаемым частоколом. Поперёк — все стопки на одном
// удалении от камеры, а два ряда разделяют стороны набора.
//
// ya/my — координата z своего ряда. «Старт» стоит седьмым в ряду «Я». Отдельного
// зазора у него больше нет: ряд из семи стопок с одной раздвинутой парой читается как
// сбитая раскладка, а не как выделенный раздел. Шаг по всему ряду один.
//
// Шаг вдоль ряда больше ширины карты, расстояние между рядами больше её высоты:
// стопки нигде не перекрываются, поэтому все тринадцать подписей целы, а плоскости
// не спорят за глубину.
export const DECK_BOX = { ya: -0.575, my: -0.415, dx: 0.112, gap: 0, perRow: 6 };

// Коробка жетонов, лоток звёзд и лоток миплов стоят одной кучкой слева от поля, в
