// Цикл замкнут: после Деятельности идёт Среда следующего витка, и это уже новый уровень
// ЗВЕЗДЫ. Один полный оборот = подъём на уровень.
export function nextPhase(id) {
    const index = PHASES.findIndex((phase) => phase.id === id);
    if (index < 0) return null;
    return PHASES[(index + 1) % PHASES.length];
}
