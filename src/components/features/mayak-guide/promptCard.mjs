//
// Это ручная разметка одной карты-образца, а не парсер. Карты набора — растры, текста в
// машиночитаемом виде у них нет, поэтому фрагмент и его место на карте заданы здесь
// руками. Так же сделан разбор анатомии карты (cardPins.mjs) — та же природа данных,
// тот же способ хранения.
//
// box — прямоугольник фрагмента на лице карты: left, top, width, height в процентах от
