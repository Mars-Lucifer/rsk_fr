export function lessonById(id) {
    return LESSONS.find((lesson) => lesson.id === id) || null;
}

// Раскладка группы по столам. Стол — шесть человек и шесть ролей; при некомплекте роли
// не дублируются, а выпадают, и первыми выпадают не инспектор с капитаном: без инспектора
// соседний стол встаёт, без капитана расходится дисциплина.
export const ROLE_DROP_ORDER = ["Летописец", "Инженер", "Хранитель Маяка", "Медиатор"];

export function tableSplit(people) {
    const count = Math.max(0, Math.floor(Number(people) || 0));
    if (!count) return { tables: 0, full: 0, rest: 0, dropped: [], warning: "" };

    const tables = Math.ceil(count / 6);
    const full = Math.floor(count / 6);
    const rest = count % 6;
    const dropped = rest ? ROLE_DROP_ORDER.slice(0, 6 - rest) : [];

    // Кольцо проверки замыкается только на трёх столах и больше. На двух инспекторы
    // проверяют друг друга — это работает, но на одном столе проверять некому.
    let warning = "";
    if (tables === 1) warning = "Один стол: кольца проверки нет, вердикты выносит мастер.";
    else if (rest && rest < 4) warning = `Неполный стол на ${rest} человек — лучше добить до четырёх или распустить по остальным.`;

    return { tables, full, rest, dropped, warning };
}
