import dynamic from "next/dynamic";
import Head from "next/head";

// Весь набор МАЯКа на одном столе в настоящем 3D: поле, жетоны, колода заданий, звёзды,
// миплы и карты ролей стоят на постоянных местах. Партия идёт сама — это те же две
// раскладки, что показывают 2D-плееры на /mayak-guide, только разыгрывают их вещи.
//
// Страница — только сцена, во весь экран. Шапки с заголовком и меню здесь нет намеренно:
// она съедала верхнюю полосу кадра, из-за чего ряд разбора у ближней кромки поля уходил
// за нижний край. Название стороны и ссылка на текстовое руководство живут в накладках
// самой сцены.
//
// Сцена грузится только на клиенте, иначе three и wasm физики уедут в общий бандл портала.
// Без заглушки на время загрузки: сцена приезжает секунду-две, и надпись на пустом экране
// успевала мигнуть при каждом обновлении страницы. Фон под сценой того же цвета, что и
// сама сцена, поэтому пустой кадр читается как ещё не накрытый стол, а не как поломка.
const MayakTable3D = dynamic(() => import("@/components/features/mayak-guide/MayakTable3D"), {
    ssr: false,
    loading: () => null,
});

export default function MayakGuide3D() {
    return (
        <>
            <Head>
                <title>МАЯК · стол мастера в 3D</title>
            </Head>
            <main>
                <MayakTable3D />
            </main>

            <style jsx>{`
                main {
                    display: block;
                    height: 100vh;
                    background: #15110e;
                    color: #f4efe6;
                    border: 0;
                    box-shadow: none;
                    overflow: hidden;
                }
            `}</style>
        </>
    );
}
